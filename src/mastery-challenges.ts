export function challengeQuestionsForLevel(level: Level): MasteryChallengeQuestion[] {
  return masteryChallengeQuestions.filter((question) => question.level === level);
}

export function pickMasteryChallenge(
  level: Level,
  randomInt?: RandomInt,
): MasteryChallengeQuestion[] {
  return pickMany(challengeQuestionsForLevel(level), masteryChallengeSize, randomInt);
}

export function isCorrectChallengeOption(
  question: MasteryChallengeQuestion,
  optionId: string,
): boolean {
  return question.correctOptionId === optionId;
}

export function assertMasteryChallengeBank(
  bank: readonly MasteryChallengeQuestion[] = masteryChallengeQuestions,
): void {
  const ids = new Set<string>();

  for (const level of levels) {
    const levelQuestions = bank.filter((question) => question.level === level);

    if (levelQuestions.length < 8) {
      throw new Error(`Level ${level} needs at least 8 mastery challenge questions`);
    }
  }

  for (const question of bank) {
    if (ids.has(question.id)) {
      throw new Error(`Duplicate mastery challenge question id: ${question.id}`);
    }

    ids.add(question.id);

    if (question.options.length !== 4) {
      throw new Error(`${question.id} must have exactly four options`);
    }

    if (!question.options.some((option) => option.id === question.correctOptionId)) {
      throw new Error(`${question.id} has no matching correct option`);
    }

    if (new Set(question.options.map((option) => option.id)).size !== question.options.length) {
      throw new Error(`${question.id} has duplicate option ids`);
    }
  }
}

