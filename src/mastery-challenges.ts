const optionIds = ["option-a", "option-b", "option-c", "option-d"] as const;

function challenge(
  id: string,
  level: Level,
  prompt: string,
  correctIndex: number,
  choices: [string, string, string, string],
  explanation: string,
): MasteryChallengeQuestion {
  const options: Option[] = choices.map((text, index) => ({ id: optionIds[index], text }));

  return {
    id,
    level,
    prompt,
    options,
    correctOptionId: optionIds[correctIndex],
    explanation,
  };
}

